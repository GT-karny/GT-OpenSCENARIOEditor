/**
 * Syncs the gRPC service .proto definitions from the GT_Sim (esmini) fork,
 * which is the single source of truth for these files.
 *
 * Source of truth: Thirdparty/GT_Sim/GT_esmini/proto/*.proto (the esmini fork
 * submodule). Override with the GT_SIM_PROTO_DIR env var if the fork lives
 * elsewhere.
 *
 * Why this script transforms the sources instead of copying them verbatim:
 * the fork imports OSI messages with an `osi3/` path prefix
 * (`import "osi3/osi_groundtruth.proto"`), matching the fork's build layout
 * where the OSI protos sit under an `osi3/` directory. The editor consumes
 * OSI from the flat `Thirdparty/open-simulation-interface` submodule, where the
 * proto files live at the directory root with no `osi3/` prefix (and their own
 * cross-imports are prefix-less too). There is no portable include-dir layout
 * that resolves the prefixed path against the flat submodule, so this script
 * mechanically rewrites `import "osi3/<name>.proto"` -> `import "<name>.proto"`
 * and prepends a generated-file header. The service/package definitions are
 * otherwise copied byte-for-byte.
 *
 * Run: pnpm --filter @osce/esmini proto:sync
 */

import { readFileSync, writeFileSync, existsSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(__dirname, '..');
const destDir = resolve(pkgRoot, 'proto');

const forkProtoDir =
  process.env.GT_SIM_PROTO_DIR ??
  resolve(pkgRoot, '../../Thirdparty/GT_Sim/GT_esmini/proto');

const PROTOS = ['service_groundtruth.proto', 'service_hostvehicledata.proto'];

const HEADER = `// AUTO-GENERATED by scripts/sync-proto.mjs — DO NOT EDIT BY HAND.
// Source of truth: GT_Sim (esmini) fork proto/${''}<name>.proto.
// The only transform applied is the OSI import path: the fork's
// \`import "osi3/<name>.proto"\` is rewritten to \`import "<name>.proto"\` to
// match the editor's flat open-simulation-interface submodule layout.
// To update: edit the fork proto, then run \`pnpm --filter @osce/esmini proto:sync\`.
`;

if (!existsSync(forkProtoDir)) {
  console.error(`Fork proto dir not found: ${forkProtoDir}`);
  console.error('Set GT_SIM_PROTO_DIR or init the Thirdparty/GT_Sim submodule.');
  process.exit(1);
}

for (const name of PROTOS) {
  const srcPath = resolve(forkProtoDir, name);
  if (!existsSync(srcPath)) {
    console.error(`Missing source proto: ${srcPath}`);
    process.exit(1);
  }
  const original = readFileSync(srcPath, 'utf-8');
  const transformed = original.replace(/import\s+"osi3\/([^"]+\.proto)"/g, 'import "$1"');
  const header = HEADER.replace('<name>', name.replace(/\.proto$/, ''));
  writeFileSync(resolve(destDir, name), header + '\n' + transformed, 'utf-8');
  console.log(`Synced ${name} (osi3/ import prefix stripped).`);
}
